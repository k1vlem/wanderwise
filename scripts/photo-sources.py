def entry(pid, src, kind):
    e = {'id': pid, 'kind': kind}
    if pid in PINNED:
        e['file'] = PINNED[pid]
    elif isinstance(src, dict):
        e.update(src)
    else:
        e['wiki'] = src
    return e


